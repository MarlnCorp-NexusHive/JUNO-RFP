export function packToPlainText(pack) {
  const lines = [`${pack.title}`, pack.subtitle, ""];
  if (pack.audience) lines.push(`Audience: ${pack.audience}`, "");
  for (const section of pack.sections) {
    lines.push(section.heading, "");
    for (const p of section.paragraphs || []) lines.push(p, "");
    for (const b of section.bullets || []) lines.push(`• ${b}`);
    if (section.bullets?.length) lines.push("");
  }
  return lines.join("\n").trim();
}

export function packToExtractedQAs(pack) {
  return (pack.sections || []).map((section) => ({
    question: section.heading,
    answer: [
      ...(section.paragraphs || []),
      ...(section.bullets || []).map((b) => `• ${b}`),
    ].join("\n\n"),
  }));
}
