function listAwardsForCalendar() {
  if (isDemoProposalManagerSession()) return DEMO_AWARDS;
  return getAwardManagementData().awards || [];
}

/** Award management next deadlines / period ends. */
export function awardItemsToCalendarEvents() {
  return listAwardsForCalendar()
    .flatMap((award) => {
      const events = [];
      const nextIso = parseDateToISO(award.nextDeadlineIso);
      if (nextIso) {
        const label = award.nextDeadlineLabel || "Next deadline";
        events.push({
          id: `award-next-${award.id}`,
          title: `${label}: ${award.title}`,
          start: nextIso,
          allDay: true,
          type: "deadline",
          color: AWARD_DEADLINE_COLOR,
          bidName: award.title,
          description: [award.funder, label].filter(Boolean).join(" · "),
          source: "award",
          awardId: award.id,
          autoGenerated: true,
        });
      }
      const endIso = parseDateToISO(award.periodEnd);
      if (endIso && endIso !== nextIso) {
        events.push({
          id: `award-end-${award.id}`,
          title: `Period end: ${award.title}`,
          start: endIso,
          allDay: true,
          type: "deadline",
          color: AWARD_DEADLINE_COLOR,
          bidName: award.title,
          description: [award.funder, "End of period"].filter(Boolean).join(" · "),
          source: "award",
          awardId: award.id,
          autoGenerated: true,
        });
      }
      return events;
    })
    .filter(Boolean);
}

function resolvePursuitCloseDeadline(pursuit) {
  const direct = parseDateToISO(pursuit?.deadline);
  if (direct) return direct;
  const needles = [pursuit?.briefKey, pursuit?.opportunityId, pursuit?.title]
    .map((v) => String(v || "").trim().toLowerCase())
    .filter(Boolean);
  const short = listShortlist().find((item) => {
    const keys = [item.id, item.number, item.opportunityId, item.title]
      .map((v) => String(v || "").trim().toLowerCase())
      .filter(Boolean);
    return needles.some((n) => keys.some((k) => k === n || k.includes(n) || n.includes(k)));
  });
  return parseDateToISO(short?.deadline);
}

/** Grant pursuit plan item due dates + primary grant deadline. */
export function pursuitItemsToCalendarEvents() {
  const events = [];
  for (const pursuit of listGrantPursuits()) {
    if (!pursuit?.startedAt) continue;
    const title = pursuit.title || pursuit.briefKey || "Grant pursuit";
    const closeIso = resolvePursuitCloseDeadline(pursuit);
    if (closeIso) {
      events.push({
        id: `pursuit-close-${pursuit.briefKey}`,
        title: `Grant deadline: ${title}`,
        start: closeIso,
        allDay: true,
        type: "deadline",
        color: SHORTLIST_DEADLINE_COLOR,
        bidName: title,
        description: [pursuit.source, pursuit.opportunityId].filter(Boolean).join(" · "),
        source: "pursuit",
        briefKey: pursuit.briefKey,
        autoGenerated: true,
      });
    }
    const plan = pursuit.plan || {};
    for (const category of PLAN_CATEGORIES) {
      const items = Array.isArray(plan[category]) ? plan[category] : [];
      for (const item of items) {
        if (item?.done) continue;
        const iso = parseDateToISO(item.dueDate);
        if (!iso) continue;
        if (closeIso && iso === closeIso) continue;
        events.push({
          id: `pursuit-${pursuit.briefKey}-${item.id}`,
          title: `${item.label}: ${title}`,
          start: iso,
          allDay: true,
          type: "milestone",
          color: PURSUIT_DEADLINE_COLOR,
          bidName: title,
          description: [category, item.detail].filter(Boolean).join(" · "),
          source: "pursuit",
          briefKey: pursuit.briefKey,
          autoGenerated: true,
        });
      }
    }
  }
  return events;
}

