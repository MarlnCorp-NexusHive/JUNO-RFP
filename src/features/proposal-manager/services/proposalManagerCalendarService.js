const SHORTLIST_DEADLINE_COLOR = "#dc2626";
const ASSIGNMENT_DEADLINE_COLOR = "#2563eb";
const SOURCE_DOC_DEADLINE_COLOR = "#b91c1c";
const AWARD_DEADLINE_COLOR = "#0f766e";
const PURSUIT_DEADLINE_COLOR = "#7c3aed";
const RFP_DEADLINE_COLOR = "#c2410c";

function findBriefKeyForShortlistItem(item) {
  if (!item) return "";
  const pursuits = listGrantPursuits();
  const needles = [item.id, item.number, item.opportunityId, item.title]
    .map((v) => String(v || "").trim().toLowerCase())
    .filter(Boolean);
  const match = pursuits.find((p) => {
    const keys = [p.briefKey, p.opportunityId, p.title]
      .map((v) => String(v || "").trim().toLowerCase())
      .filter(Boolean);
    return needles.some((n) => keys.some((k) => k === n || k.includes(n) || n.includes(k)));
  });
  return match?.briefKey || "";
}

/** Map shortlisted grants/RFPs to all-day calendar deadline events. */
export function shortlistItemsToCalendarEvents() {
  return listShortlist()
    .map((item) => {
      const iso = parseDateToISO(item.deadline);
      if (!iso) return null;
      const sourceLabel = SHORTLIST_SOURCE_LABELS[item.source] || "Grant";
      const briefKey = findBriefKeyForShortlistItem(item);
      return {
        id: shortlistEventId(item.id),
        title: `${sourceLabel} deadline: ${item.title}`,
        start: iso,
        allDay: true,
        type: "deadline",
        color: SHORTLIST_DEADLINE_COLOR,
        bidName: item.number || item.title,
        description: [item.agency, item.number].filter(Boolean).join(" · "),
        source: "shortlist",
        shortlistId: item.id,
        briefKey: briefKey || undefined,
        autoGenerated: true,
      };
    })
    .filter(Boolean);
}

